#!/usr/bin/env python3
"""Generate the requirement -> case -> callback matrix from the successor registry and two baseline results.
NONPRODUCTION. Nothing is typed by hand: requirement text, needs and required flags come from harness.CASES;
verdicts come from the named result files. usage: make_matrix.py --proto-l RES.json --staged-g RES.json --out MATRIX.md
"""

import argparse
import inspect
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import harness  # noqa: E402

CHANGED = {"CAP-4": "H1 implemented", "RP-1": "H1 implemented", "RP-2": "H1 implemented", "IN-2": "H1 implemented",
           "ST-1": "H3 reason required", "ST-2": "H3 reason required", "ST-3": "H3 reason required", "ST-4": "new control",
           "N7-3": "new (#04)", "LR-6": "#04 destination"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--proto-l", required=True)
    ap.add_argument("--staged-g", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    res = {k: {r["id"]: r["verdict"] for r in json.loads(Path(p).read_text(encoding="utf-8"))["records"]}
           for k, p in (("proto-l", a.proto_l), ("staged-g", a.staged_g))}
    lines = ["# MATRIX — requirement → case → callback (generated by make_matrix.py; harness successor 0707/05.22)", "",
             f"Full required baseline: {len(harness.full_required(harness.CASES))} cases (immutable; `--suite` cannot shrink it). "
             "Every required case has an executable callback; none returns an unconditional `not-run` (test_verdict U40).", "",
             "| Case | Group | Req | Needs | Change | Callback | proto-l | staged-g | Requirement |",
             "|---|---|---|---|---|---|---|---|---|"]
    for c in harness.CASES:
        fn = c["fn"].__name__
        lines.append(f"| {c['id']} | {c['group']} | {'yes' if c['required'] else 'KF'} | {','.join(c['needs']) or '-'} | {CHANGED.get(c['id'], '')} | "
                     f"`{fn}` (line {inspect.getsourcelines(c['fn'])[1]}) | {res['proto-l'].get(c['id'], '-')} | {res['staged-g'].get(c['id'], '-')} | "
                     f"{c['requirement'].replace('|', '/')} |")
    lines += ["", "`blocked` = a dependency is pending, so the case is not executed. `KF` = a known-failure record, never counted toward readiness.",
              "In-suite `blocked` cases were also executed as labelled probes (probe.py) on both baselines; see RESULTS.md."]
    Path(a.out).write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(a.out)


if __name__ == "__main__":
    main()
