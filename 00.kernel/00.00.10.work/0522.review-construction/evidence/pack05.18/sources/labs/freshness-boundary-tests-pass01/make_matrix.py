#!/usr/bin/env python3
"""Generate MATRIX.md (requirement -> case -> observed per baseline -> prediction class) from the registry, the two
result files and the two reconcile files. Nothing is typed by hand. NONPRODUCTION.
usage: make_matrix.py --evidence DIR --out MATRIX.md"""

import argparse
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import run as R  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--evidence", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    E = Path(a.evidence)
    res, rec = {}, {}
    for k in ("proto-l", "staged-g"):
        res[k] = {r["id"]: r for r in json.loads((E / f"run-{k}-01.json").read_text(encoding="utf-8"))["records"]}
        rec[k] = {r["id"]: r for r in json.loads((E / f"reconcile-{k}.json").read_text(encoding="utf-8"))["rows"]}
    helper = json.loads((E / "helper-regions-run01.json").read_text(encoding="utf-8"))["cases"]
    L = ["# MATRIX — freshness-boundary cases (generated by make_matrix.py from results; 0707/05.23)", "",
         f"{len(R.CASES)} cases, {sum(c['required'] for c in R.CASES)} required (F4 observational, D1 deferred). "
         "`not-reached` = the fixture was refused before record; it is never credited.", "",
         "| Case | Group | Req | Requirement | proto-l | staged-g | Prediction (proto-l / staged-g) | L helper |",
         "|---|---|---|---|---|---|---|---|"]
    for c in R.CASES:
        cid = c["id"]
        h = helper.get(cid, {})
        hs = "-" if not h.get("applies") else ("exempts" if h["helper_exempts_edit"] else "bound changes")
        cls = " / ".join(rec[k][cid]["class"] for k in ("proto-l", "staged-g"))
        L.append(f"| {cid} | {c['group']} | {'yes' if c['required'] else 'no'} | {c['requirement'].replace('|', '/')} | "
                 f"{res['proto-l'][cid]['verdict']} | {res['staged-g'][cid]['verdict']} | {cls} | {hs} |")
    Path(a.out).write_bytes(("\n".join(L) + "\n").encode("utf-8"))
    print(a.out)


if __name__ == "__main__":
    main()
