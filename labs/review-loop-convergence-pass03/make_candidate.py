def make_candidate(output: Path) -> dict:
    output = Path(output)
    if output.exists():
        refuse(f"output is occupied: {output}")
    try:
        output.resolve().relative_to(REPO.resolve())
    except ValueError:
        pass
    else:
        refuse("output root is inside the live repo")
    workbook = (LAB / "workbook.py").read_bytes()
    report = (LAB / "report.py").read_bytes()
    if b"\r" in workbook or b"\r" in report:
        refuse("proposal has CR")
    before_active = ACTIVE.read_bytes()
    before_pass02 = (REPO / "labs" / "review-loop-convergence-pass02" / "workbook.py").read_bytes()
    masked = render_librarian()
    masked_sha = sha(masked)
    declaration = render_declaration(workbook)
    loop_door = render_loop_door(workbook, declaration)
    report_door = render_report_door(masked_sha, len(masked), workbook, report)
    anchor = render_anchor(loop_door, report_door)
    anchor_sha = sha(anchor)
    librarian = masked.replace(f'ANCHOR_SHA = "{ZEROS}"'.encode("utf-8"), f'ANCHOR_SHA = "{anchor_sha}"'.encode("utf-8"), 1)
    if sha(_masked(librarian)) != masked_sha or len(librarian) != len(masked):
        refuse("masked dispatcher hash moved when the anchor literal was written")
    if anchor_sha.encode("utf-8") in anchor:
        refuse("trust anchor stores its own hash")
    copies = _copies()
    mapping = {
        WORKBOOK_REL: workbook,
        REPORT_REL: report,
        LOOP_REL: loop_door,
        REPORT_DOOR_REL: report_door,
        DECLARATION_REL: declaration,
        ANCHOR_REL: anchor,
        ENTRY: librarian,
    }
    roles = {
        ENTRY: "entry",
        WORKBOOK_REL: "workbook",
        REPORT_REL: "reporter",
        LOOP_REL: "adapter",
        REPORT_DOOR_REL: "adapter",
        DECLARATION_REL: "declaration",
        ANCHOR_REL: "data",
    }
    for rel, data in copies.items():
        mapping[rel] = data
        roles[rel] = "dependency"
    for rel, data in mapping.items():
        if str(output).encode("utf-8") in data or str(output).replace("\\", "/").encode("utf-8") in data:
            refuse(f"generated file embedded the output root: {rel}")
        _write(output / rel, data)
    dependencies = _imports(output / WORKBOOK_REL)
    files = [_row(rel, data, roles[rel]) for rel, data in sorted(mapping.items())]
    document = _candidate_document(files, dependencies, masked_sha)
    if str(output) in document.decode("utf-8"):
        refuse("candidate descriptor embedded the output root")
    _write(output / "CANDIDATE.json", document)
    _harness(output, document, files, dependencies)
    if ACTIVE.read_bytes() != before_active or (REPO / "labs" / "review-loop-convergence-pass02" / "workbook.py").read_bytes() != before_pass02:
        refuse("builder changed a sealed file")
    return {
        "candidate_json_sha256": sha(document),
        "files": len(files),
        "dependencies": len(dependencies),
    }


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if args[:1] != ["--root"] or len(args) != 2 or args[1] == "":
        refuse("usage: make_candidate.py --root ABS")
    made = make_candidate(Path(args[1]))
    print(f"{made['candidate_json_sha256']} files {made['files']} dependencies {made['dependencies']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
