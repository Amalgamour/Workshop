def items(text):
    """Yield (header line, reply text or None) per #NN item."""
    lines = text.split("\n")
    cur, reply, grab = None, None, False
    for ln in lines + ["#00 >end"]:
        if re.match(r"^#\d{2} [>a-z]", ln):
            if cur is not None:
                yield cur, (reply.rstrip("\n") if reply is not None else None)
            cur, reply, grab = ln, None, False
            m = re.match(r"^#\d{2} reply:\s?(.*)$", ln)
            if m:
                reply, grab = m.group(1), True
            continue
        if cur is None:
            continue
        if ln.startswith("reply:"):
            reply, grab = ln[len("reply:"):].lstrip(" "), True
            continue
        if grab:
            if ln.startswith("status:") or re.match(r"^(placed|issue|recommend|path|scale|Ask|reason):", ln):
                grab = False
                continue
            reply += "\n" + ln


def quote(s):
    return "\n".join("> " + x if x else ">" for x in s.split("\n"))


